import { IsNotEmpty, IsOptional, IsString, Matches, MaxLength } from 'class-validator';
import { Transform } from 'class-transformer';

export class AddWhatsappNumberDto {
    /** From Meta's WhatsApp → API Setup page, labelled "Phone number ID". */
    @Matches(/^\d{5,30}$/, { message: 'phone_number_id is the numeric ID Meta shows, not the phone number' })
    phone_number_id: string;

    @IsOptional()
    @IsString()
    @IsNotEmpty()
    @MaxLength(30)
    display_phone?: string;
}

export class TestChatDto {
    @Transform(({ value }) => (typeof value === 'string' ? value.trim() : value))
    @IsString()
    @IsNotEmpty()
    @MaxLength(1000)
    message: string;

    /** Generated by the page; a new one starts a fresh conversation. */
    @Matches(/^[\w-]{8,64}$/)
    session_id: string;

    /** The number the test lead's client is filed under. */
    @Matches(/^\+?[\d\s-]{8,20}$/, { message: 'Enter a phone number with the country code' })
    phone: string;

    @IsOptional()
    @IsString()
    @MaxLength(100)
    name?: string;
}
